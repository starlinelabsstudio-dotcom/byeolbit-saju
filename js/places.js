  function norm(s) { return String(s || '').replace(/[\s·,.\-()]/g, ''); }
  function baseName(n) { return n.replace(/\(.*\)/, '').replace(/(특별자치시|특별자치도|특별시|광역시)$/, '').replace(/[시군구]$/, ''); }

