  function findProv(t) {
    var found = [];
    for (var i = 0; i < PROV.length; i++) {
      var names = [PROV[i][0]].concat(PROV[i][1]);
      for (var j = 0; j < names.length; j++) if (t.indexOf(norm(names[j])) >= 0) { found.push(i); break; }
    }
    if (!found.length) return -1;
    var dos = found.filter(function (i) { return i >= 8; });
    return dos.length ? dos[0] : found[0];
  }

